// Validate key symmetry between va, es, en
function compareKeys(obj1, obj2, prefix = '') {
  for (const k of Object.keys(obj1)) {
    const fullKey = prefix ? `${prefix}.${k}` : k;
    if (!(k in obj2)) {
      console.error(`Missing key in target: ${fullKey}`);
      process.exit(1);
    }
    if (typeof obj1[k] === 'object' && obj1[k] !== null) {
      compareKeys(obj1[k], obj2[k], fullKey);
    }
  }
}

console.log('Comparing VA to ES...');
compareKeys(newVa, newEs);
console.log('Comparing VA to EN...');
compareKeys(newVa, newEn);
console.log('Keys are 100% matched across all 3 languages!');

